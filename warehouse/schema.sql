CREATE DATABASE IF NOT EXISTS TALENTPULSE;
USE DATABASE TALENTPULSE;

CREATE SCHEMA IF NOT EXISTS JOB_ANALYTICS;
USE SCHEMA JOB_ANALYTICS;

CREATE TABLE IF NOT EXISTS DIM_COMPANY (
    COMPANY_ID INTEGER AUTOINCREMENT PRIMARY KEY,
    COMPANY_NAME STRING NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS DIM_LOCATION (
    LOCATION_ID INTEGER AUTOINCREMENT PRIMARY KEY,
    LOCATION_NAME STRING NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS DIM_ROLE (
    ROLE_ID INTEGER AUTOINCREMENT PRIMARY KEY,
    ROLE_NAME STRING NOT NULL,
    CATEGORY STRING,
    EXPERIENCE_LEVEL STRING
);

CREATE TABLE IF NOT EXISTS DIM_SKILL (
    SKILL_ID INTEGER AUTOINCREMENT PRIMARY KEY,
    SKILL_NAME STRING NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS FACT_JOBS (
    JOB_ID INTEGER AUTOINCREMENT PRIMARY KEY,
    COMPANY_ID INTEGER NOT NULL,
    LOCATION_ID INTEGER NOT NULL,
    ROLE_ID INTEGER NOT NULL,
    JOB_TITLE STRING NOT NULL,
    JOB_TYPE STRING,
    WORK_MODE STRING,
    SALARY_MIN NUMBER,
    SALARY_MAX NUMBER,
    JOB_URL STRING,
    POSTED_DATE DATE,
    SOURCE_JOB_ID STRING,
    FOREIGN KEY (COMPANY_ID) REFERENCES DIM_COMPANY(COMPANY_ID),
    FOREIGN KEY (LOCATION_ID) REFERENCES DIM_LOCATION(LOCATION_ID),
    FOREIGN KEY (ROLE_ID) REFERENCES DIM_ROLE(ROLE_ID)
);

CREATE TABLE IF NOT EXISTS FACT_JOB_SKILLS (
    JOB_ID INTEGER NOT NULL,
    SKILL_ID INTEGER NOT NULL,
    PRIMARY KEY (JOB_ID, SKILL_ID),
    FOREIGN KEY (JOB_ID) REFERENCES FACT_JOBS(JOB_ID),
    FOREIGN KEY (SKILL_ID) REFERENCES DIM_SKILL(SKILL_ID)
);
